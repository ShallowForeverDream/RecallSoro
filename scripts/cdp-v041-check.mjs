const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const targets = await fetch('http://127.0.0.1:9222/json').then((r) => r.json());
const page = targets.find((t) => t.type === 'page' && t.url.includes('127.0.0.1:4173'));
const ws = new WebSocket(page.webSocketDebuggerUrl);
await new Promise((res) => { ws.onopen = res; });
let seq = 0;
const pending = new Map();
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } };
const send = (method, params = {}) => new Promise((resolve) => { const id = ++seq; pending.set(id, resolve); ws.send(JSON.stringify({ id, method, params })); });
const ev = async (x) => { const r = await send('Runtime.evaluate', { expression: x, returnByValue: true, awaitPromise: true }); if (r.result?.exceptionDetails) throw new Error(r.result.exceptionDetails.text); return r.result?.result?.value; };
await send('Runtime.enable');
await sleep(800);
console.log('nav:', await ev("[...document.querySelectorAll('.nav-item span')].map(e=>e.textContent).join(' | ')"));
let text = await ev('document.body.innerText');
console.log('dashboard keywords:', ['总览','年度','缺证书','待核实','未整理','智能建议'].map(k=>`${k}:${text.includes(k)}`).join(' '));
console.log('buttons:', await ev("[...document.querySelectorAll('button')].map(b=>b.textContent.trim()).filter(Boolean).slice(0,35).join(' || ')"));
await ev("location.href='http://127.0.0.1:4173/collections'");
await sleep(600);
await ev("(()=>{const b=[...document.querySelectorAll('.list-card,button')].find(x=>x.textContent.includes('全部竞赛经历'));if(b){b.click();return true}return false})()");
await sleep(800);
text = await ev('document.body.innerText');
console.log('ledger buttons:', await ev("[...document.querySelectorAll('button')].map(b=>b.textContent.trim()).filter(Boolean).slice(0,30).join(' || ')"));
console.log('has PDF export:', text.includes('证明') || text.includes('PDF'));
const rowClicked = await ev("(()=>{const r=[...document.querySelectorAll('tr,[role=row]')].find(x=>x.textContent.includes('蓝桥杯'));if(r){r.click();return true}return false})()");
await sleep(500);
text = await ev('document.body.innerText');
console.log('row clicked:', rowClicked, '| history/redaction:', text.includes('历史') || text.includes('脱敏'));
ws.close();
